-- V1: Initial schema.
--
-- This is an exact snapshot of the schema Hibernate created before Flyway was
-- introduced, including the generated constraint names. Existing databases can
-- therefore be baselined at version 1 without this migration modifying them.
-- V2 then normalizes the generated names and adds indexes.

CREATE TABLE users (
    id uuid NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    email character varying(255) NOT NULL,
    enabled boolean NOT NULL,
    first_name character varying(255) NOT NULL,
    last_name character varying(255),
    password character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email)
);

CREATE TABLE categories (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    description character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    transaction_type character varying(255),
    CONSTRAINT categories_pkey PRIMARY KEY (id),
    CONSTRAINT ukt8o6pivur7nn124jehx7cygw5 UNIQUE (name),
    CONSTRAINT categories_transaction_type_check
        CHECK (transaction_type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE transactions (
    id uuid NOT NULL,
    amount numeric(19, 2) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    description character varying(500),
    transaction_date timestamp(6) without time zone NOT NULL,
    type character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    category_id integer NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT transactions_pkey PRIMARY KEY (id),
    CONSTRAINT transactions_type_check CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT fkqwv7rmvc8va8rep7piikrojds
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fksqqi7sneo04kast0o138h19mv
        FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE budgets (
    id uuid NOT NULL,
    amount numeric(19, 2) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    budget_month character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    budget_year integer NOT NULL,
    category_id integer NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT budgets_pkey PRIMARY KEY (id),
    CONSTRAINT uk_budget_user_category_month_year
        UNIQUE (user_id, category_id, budget_month, budget_year),
    CONSTRAINT budgets_budget_month_check
        CHECK (budget_month IN (
            'JANUARY', 'FEBRUARY', 'MARCH', 'APRIL', 'MAY', 'JUNE',
            'JULY', 'AUGUST', 'SEPTEMBER', 'OCTOBER', 'NOVEMBER', 'DECEMBER'
        )),
    CONSTRAINT fkln0tm5tgf3f9q3sp9sa5m8m7b
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fkn7qib00712y8dwelmqfwis6ka
        FOREIGN KEY (category_id) REFERENCES categories (id)
);
